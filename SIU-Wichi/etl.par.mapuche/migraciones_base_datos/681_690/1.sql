--Agregar parametro a instalaciones
CREATE OR REPLACE FUNCTION public.agregar_parametros()
RETURNS void AS
$BODY$
			DECLARE
				instalacion RECORD;	
				cur_instalacion CURSOR FOR SELECT distinct instalacion_id FROM public.parametro_instalacion
			where instalacion_id not in (SELECT distinct instalacion_id FROM public.parametro_instalacion where nombre = 'plataforma');
			BEGIN
				
				FOR instalacion IN cur_instalacion LOOP
				INSERT INTO public.parametro_instalacion(instalacion_id, nombre, valor) VALUES (instalacion.instalacion_id, 'plataforma', '');
				INSERT INTO public.parametro_instalacion(instalacion_id, nombre, valor) VALUES (instalacion.instalacion_id, 'motor', '(sin motor)');
				END LOOP;
			END;
			$BODY$
  LANGUAGE plpgsql VOLATILE
  COST 100;
ALTER FUNCTION public.agregar_parametros()
  OWNER TO postgres;

Select public.agregar_parametros();

DROP FUNCTION public.agregar_parametros();

